import os
import yaml
from collections import Counter

def load_yaml(filepath):
    with open(filepath, 'r') as f:
        return yaml.safe_load(f)

def analyze_datasets(dataset_dir):
    single_turn_files = [f for f in os.listdir(dataset_dir) if f.endswith('.yaml')]
    multi_turn_dir = os.path.join(dataset_dir, 'multi_turn')
    multi_turn_files = [f for f in os.listdir(multi_turn_dir) if f.endswith('.yaml')]
    
    # Metrics
    categories = Counter()
    severities = Counter()
    owasp = Counter()
    total_single_turn = 0
    total_multi_turn = 0
    total_multi_turn_steps = 0
    
    # Process Single Turn
    for file in single_turn_files:
        data = load_yaml(os.path.join(dataset_dir, file))
        if not data:
            continue
        for item in data:
            total_single_turn += 1
            categories[item.get('category', 'unknown')] += 1
            severities[item.get('severity', 'unknown').upper()] += 1
            owasp[item.get('owasp_category', 'unknown')] += 1
            
    # Process Multi Turn
    for file in multi_turn_files:
        data = load_yaml(os.path.join(multi_turn_dir, file))
        if not data:
            continue
        total_multi_turn += 1
        categories[data.get('category', 'unknown')] += 1
        severities[data.get('severity', 'unknown').upper()] += 1
        total_multi_turn_steps += len(data.get('turns', []))
        
    return {
        "total_single_turn_prompts": total_single_turn,
        "total_multi_turn_campaigns": total_multi_turn,
        "total_multi_turn_steps": total_multi_turn_steps,
        "severities": dict(severities),
        "categories": dict(categories),
        "owasp_categories": dict(owasp)
    }

def generate_report(metrics, output_path):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    with open(output_path, 'w') as f:
        f.write("# 📊 Dataset Analysis Report\n\n")
        f.write("This report provides a statistical breakdown of the adversarial AI datasets used in the SentinelForge red-teaming lab.\n\n")
        
        f.write("## 📈 Overall Metrics\n")
        f.write(f"- **Total Single-Turn Prompts**: {metrics['total_single_turn_prompts']}\n")
        f.write(f"- **Total Multi-Turn Campaigns**: {metrics['total_multi_turn_campaigns']}\n")
        f.write(f"- **Total Multi-Turn Steps**: {metrics['total_multi_turn_steps']}\n\n")
        
        f.write("## ⚠️ Severities Distribution\n")
        f.write("| Severity | Count |\n")
        f.write("|----------|-------|\n")
        for k, v in sorted(metrics['severities'].items(), key=lambda x: x[1], reverse=True):
            f.write(f"| {k} | {v} |\n")
        f.write("\n")
        
        f.write("## 🏷️ Attack Categories\n")
        f.write("| Category | Count |\n")
        f.write("|----------|-------|\n")
        for k, v in sorted(metrics['categories'].items(), key=lambda x: x[1], reverse=True):
            f.write(f"| {k} | {v} |\n")
        f.write("\n")
        
        f.write("## 🛡️ OWASP Classifications\n")
        f.write("| OWASP Category | Count |\n")
        f.write("|----------------|-------|\n")
        for k, v in sorted(metrics['owasp_categories'].items(), key=lambda x: x[1], reverse=True):
            f.write(f"| {k} | {v} |\n")
        f.write("\n")
        
        f.write("---\n")
        f.write("*Generated by SentinelForge Dataset Analysis Script*")

if __name__ == "__main__":
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dataset_dir = os.path.join(base_dir, 'datasets', 'attacks')
    output_path = os.path.join(base_dir, 'reports', 'dataset_analysis.md')
    
    print(f"Analyzing datasets in {dataset_dir}...")
    metrics = analyze_datasets(dataset_dir)
    
    print(f"Generating report at {output_path}...")
    generate_report(metrics, output_path)
    
    print("✅ Analysis complete!")
